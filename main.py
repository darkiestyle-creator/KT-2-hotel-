'''
# 1 - while - работает до того момента, пока true условие является таковым. как будет false - цикл остановится. for работает исключительно
уже с готовыми данными (обычно это массивы данных, условно [5,10,15,25 ...]. в том числе используются списки и диапазоны

# 2 - range() является последовательностью чисел. обычно там используется от 1 до 3 чисел. примеры: если написано range(1,5) - то будут перечислены числа от 1
до 5 (не учитывая 5). то есть, мы получим вывод: 1, 2, 3, 4. если используется 3 числа: range(1,5,2) - первые два числа будут иметь точно такую же функцию,
но уже учитывая третье число (то есть, 2 шага). если у нас в скобках 1,5 и 2 - то терминал выведет нам "1, 3, 5"

# 3 - break преждевременно заканчивает цикл, даже если он не был завершен по условиям. то есть цикл завершает работу и читает дальше код. continue используется
для пропуска шага и перехода к следующей фазе. обычно код который был до contuinue буквально "стирается", а после этого переходит по коду дальше

# 4 - бесконечный цикл - это когда код выполняется бесконечно, пока твой комп не сломается нахуй. обычно такое случается при использовании while в случаях
того, когда код не был дописан (условно, если x = 0, а потом написано что while x < 100, и после этого будет выведен принт x = программа будет спамить до
бесконечности, потому что 100 всегда больше 0. обычно это используется в программах которые должны работать постоянно (в какой-либо фазе), пока пользователь/игрок не сделает какое-либо действие, заверщающие
этот бесконечный цикл (хз например зайдет в аккаунт или выйдет с него).

# 5 - ну else выполнится только если весь предыдущий код с участием while или for закончился логично без участия break. если break будет использовано, то цикл пойдет
нахуй
'''

money = int(input("Сколько у нас денег на месяц: "))
count = 0

while True:
    answer = input("Введи расход или слово стоп: ")

    if answer == "стоп":
        break

    if answer == "":
        print("Ты ничего не ввел")
    else:
        rashod = int(answer)

        if rashod <= 0:
            print("Расход должен быть больше нуля")
        elif rashod > money:
            print("Денег нет!")
        else:
            money = money - rashod
            count = count + 1
            print("Записал! Осталось:", money)
print("Успешных трат:", count)
print("Осталось денег:", money)